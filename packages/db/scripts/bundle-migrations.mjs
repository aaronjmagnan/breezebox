/**
 * Concatenate every migration into one script you can paste into the Supabase
 * SQL editor, for a project that is not linked to the CLI.
 *
 * Prefer `pnpm db:push` when the project IS linked: that records what has been
 * applied, so the next migration knows where to start. This bundle does not.
 *
 * Usage: pnpm --filter @breezebox/db bundle
 * Output: packages/db/supabase/bundle.sql (gitignored, regenerate on demand)
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'supabase');
const migrationsDir = join(root, 'migrations');

/*
 * `--since <version>` bundles only migrations AFTER that one, for a project
 * that is already part-way applied. Without it you would have to re-run the
 * whole bundle, which fails on the first object that already exists.
 *
 *   node scripts/bundle-migrations.mjs --since 20260916091100
 */
const sinceIndex = process.argv.indexOf('--since');
const since = sinceIndex === -1 ? null : process.argv[sinceIndex + 1];

const all = readdirSync(migrationsDir)
  .filter((f) => f.endsWith('.sql'))
  .sort();

const files = since ? all.filter((f) => f.split('_')[0] > since) : all;

if (files.length === 0) {
  console.error(since ? `No migrations after ${since}.` : 'No migrations found.');
  process.exit(1);
}

const parts = [
  since
    ? `-- Breeze Box :: ${files.length} migration(s) after ${since}, concatenated.`
    : `-- Breeze Box :: all ${files.length} migrations, concatenated.`,
  '--',
  '-- GENERATED by scripts/bundle-migrations.mjs. Do not edit; edit the',
  '-- migrations and regenerate.',
  '--',
  '-- Paste into the Supabase SQL editor and run once. It is wrapped in a',
  '-- single transaction, so a failure anywhere leaves the database untouched.',
  '--',
  '-- Files, in order:',
  ...files.map((f, i) => `--   ${String(i + 1).padStart(2, ' ')}. ${f}`),
  '',
  'begin;',
  '',
];

for (const file of files) {
  parts.push(
    '-- ' + '='.repeat(74),
    `-- ${file}`,
    '-- ' + '='.repeat(74),
    '',
    readFileSync(join(migrationsDir, file), 'utf8').trimEnd(),
    '',
  );
}

parts.push('commit;', '');

const out = join(root, since ? `bundle-since-${since}.sql` : 'bundle.sql');
writeFileSync(out, parts.join('\n'));
console.log(`Wrote ${out} (${files.length} migrations)`);
